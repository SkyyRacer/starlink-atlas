"""Generate the shared browser registry from the reviewed constellation definitions."""
import json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
rows=json.loads((ROOT/'resources/constellations.json').read_text())
encoded=json.dumps(rows,ensure_ascii=False,separators=(',',':'))
source='''/* Generated by scripts/generate_constellations.py; edit resources/constellations.json. */
(function(root){
 const definitions=__DATA__;
 const byId=new Map(definitions.map(row=>[row.id,row])),identities=new Map();
 for(const row of definitions)for(const id of row.ids)identities.set(id,row.id);
 function family(s){
  const id=s.id??s.NORAD_CAT_ID,name=s.name||s.OBJECT_NAME||'';
  const debris=byId.get('debris');if(s.family==='debris'||s.object_type==='DEB'||s.object_type==='R/B'||(debris&&(debris.ids.includes(id)||debris.prefixes.some(p=>name.startsWith(p))||debris.contains.some(p=>name.includes(p)))))return 'debris';
  if(id===25544)return 'iss';if(s.family&&byId.has(s.family))return s.family;
  if(name.startsWith('STARLINK'))return 'starlink';
  if(/^(?:GPS (?:B|III)|NAVSTAR \\d)/.test(name))return 'gps';
  if(/^(?:GSAT\\d{4}(?:\\s|\\(|$)|GIOVE-[AB]|GALILEO(?:[ -]|$))/.test(name))return 'galileo';
  if(/(?: DEB| AKM| R\\/B)/.test(name))return null;
  return identities.get(id)||definitions.find(row=>row.prefixes.some(p=>name.startsWith(p))||row.contains.some(p=>name.includes(p)))?.id||null;
 }
 const api={definitions,byId,family};if(typeof module!=='undefined'&&module.exports)module.exports=api;else root.AtlasCollections=api;
})(globalThis);
'''.replace('__DATA__',encoded)
(ROOT/'static/constellations.js').write_text(source)
# Keep the menu and Atlas cards aligned with the same reviewed registry.
import html
page=ROOT/'static/index.html';text=page.read_text()
a=text.index('<option value="all">');b=text.index('</select>',a)
text=text[:a]+'<option value="all">Tous les satellites</option>'+''.join('<option value="'+r['id']+'"'+(' selected' if r['id']=='starlink' else '')+'>'+html.escape(r['label'])+'</option>' for r in rows)+text[b:]
a=text.index('<div class="atlas-family-list">');b=text.index('<p class="hint">Coche les catégories',a)
def card(row):
    key=row['id'];label=html.escape(row['label'])
    return '<div class="atlas-family-card"><label><input type="checkbox" data-family="'+key+'" checked><span><strong>'+label+'</strong><small id="atlas-count-'+key+'">—</small></span></label><div class="atlas-color-control"><input type="color" id="atlas-color-'+key+'" value="#ffffff" aria-label="Couleur : '+label+'" title="Choisir la couleur"><label for="atlas-color-'+key+'">Modifier la couleur</label></div></div>'
text=text[:a]+'<div class="atlas-family-list">'+''.join(card(row) for row in rows)+'</div>'+text[b:]
page.write_text(text)
